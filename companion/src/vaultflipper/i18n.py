import os


def _detect() -> str:
    for var in ("VAULTFLIPPER_LANG", "LC_ALL", "LC_MESSAGES", "LANG"):
        val = os.environ.get(var, "")
        if val:
            return "de" if val.lower().startswith("de") else "en"
    return "en"


