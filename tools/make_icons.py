def main() -> None:
    out = Path(__file__).resolve().parents[1] / "flipper" / "vaultflipper" / "images"
    out.mkdir(exist_ok=True)
    for name, art in ICONS.items():
        rows = [r for r in art.strip("\n").splitlines()]
        assert len(rows) == 10 and all(len(r) == 10 for r in rows), name
        img = Image.new("1", (10, 10), 1)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#":
                    img.putpixel((x, y), 0)
        img.save(out / f"{name}.png")
    print(f"{len(ICONS)} icons -> {out}")


if __name__ == "__main__":
    main()
